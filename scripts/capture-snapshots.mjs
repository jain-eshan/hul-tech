// B4 · Point-in-Time Evidence Snapshot — PRD §6 B4.
//
// Violating content gets edited or deleted before you can prove what it said. At every
// detection this captures a rendered snapshot — PNG plus DOM plus hash — so monitoring
// becomes evidence rather than an alert.
//
// The capture is real: a headless browser renders each page, expands collapsed content
// (disclosures hide there), and both artefacts are hashed with SHA-256. The pages being
// captured are local fixtures, because this environment has no outbound network.
//
// Usage:  npx next build && npx next start -p 3140 &
//         node scripts/capture-snapshots.mjs

import { chromium } from "playwright-core";
import { createHash } from "node:crypto";
import { writeFileSync, mkdirSync } from "node:fs";
import { creatorPosts } from "../data/creatorPosts.mjs";

const BASE = process.env.BASE ?? "http://localhost:3140";
const OUT = "public/snapshots";
mkdirSync(OUT, { recursive: true });

const sha256 = (buf) => "sha256-" + createHash("sha256").update(buf).digest("hex").slice(0, 32);

const browser = await chromium.launch({
  executablePath: "/opt/pw-browsers/chromium",
  args: ["--no-proxy-server"],
});
const page = await browser.newPage({ viewport: { width: 560, height: 900 }, deviceScaleFactor: 2 });

const observations = [];

for (const post of creatorPosts) {
  const url = `${BASE}/fixtures/post/${post.id}`;
  await page.goto(url, { waitUntil: "load" });

  // Expand collapsed content before capturing. Disclosures hide behind "more" folds,
  // so a snapshot taken without expanding is evidence of the wrong thing.
  const expanded = await page.evaluate(() => {
    const hidden = document.querySelectorAll('[data-collapsed="true"]');
    hidden.forEach((el) => { el.style.display = "inline"; });
    return hidden.length;
  });

  const png = await page.screenshot({ fullPage: true });
  const dom = await page.content();
  const capturedAt = new Date().toISOString();

  writeFileSync(`${OUT}/${post.id}.png`, png);
  writeFileSync(`${OUT}/${post.id}.html`, dom);

  observations.push({
    id: `OBS-${post.id}`,
    postId: post.id,
    url,
    pngRef: `/snapshots/${post.id}.png`,
    domRef: `/snapshots/${post.id}.html`,
    pngHash: sha256(png),
    domHash: sha256(Buffer.from(dom)),
    capturedAt,
    expandedRegions: expanded,
    bytes: png.length,
  });

  console.log(`captured ${post.id}  ${sha256(png)}  ${(png.length / 1024).toFixed(0)}KB  expanded=${expanded}`);
}

await browser.close();

writeFileSync(
  "data/observations.ts",
  `// GENERATED by scripts/capture-snapshots.mjs — do not edit by hand.
//
// Each row is a real headless-browser capture of the page named in \`url\`, with the
// PNG and DOM hashed at capture time. Re-run the script to refresh.

export interface Snapshot {
  id: string;
  postId: string;
  url: string;
  pngRef: string;
  domRef: string;
  pngHash: string;
  domHash: string;
  capturedAt: string;
  expandedRegions: number;
  bytes: number;
}

export const snapshots: Snapshot[] = ${JSON.stringify(observations, null, 2)};
`,
);
console.log(`\nwrote data/observations.ts with ${observations.length} snapshots`);
